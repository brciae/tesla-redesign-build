assert(client.includes('FleetCommandPolicy.accepted(data)'));
assert(client.includes('FleetCommandRedirectGuard()'));
for (const name of ['HomeViews', 'ControlViews', 'ChargingWorkspace']) {
  assert(!read(name).includes('link.askControl('), `${name} bypasses shared transport selection`);
}
assert(!read('TeslaInteractiveClimateView').includes('try? await'), 'Climate must show failures');
assert(!/func pause\(\)[^\n]*stopSpeech/.test(read('AppModel')), 'Background entry must not stop audio');
assert(!/func (pause|resignActive)\(\)[^\n]*resetObservation/.test(read('AppModel')));
assert(read('AutomationCoordinator').includes('UIApplication.shared.applicationState == .active,\n'), 'Background speech must not unlock physical automation');
assert(read('VehicleCommandRouting').includes('guard !demo'));
const navigation = read('EmbeddedNavigation');
assert(navigation.includes('func endGuidance()'));
assert(navigation.includes('stopNative(keepDisplay: keepDisplay)'));
assert(navigation.includes('if keepDisplay { startStandbyKakaoMap() }'));
assert(read('DrivingWorkspace').includes('navigation.endGuidance()'));
assert(read('AppModel').includes('navigation.onGuidanceEnd = { [weak self] in self?.voice.stop() }'));
const bridge = fs.readFileSync('TeslaLocal.swiftpm/Sources/KakaoNavigationBridge/YLKakaoController.m', 'utf8');
assert(!bridge.includes('shouldSpeak:'), 'SDK voice timing must not be suppressed by app timers');
assert(!bridge.includes('YLSpokenDistance'), 'No legacy recording distance buckets');
assert(!bridge.includes('[@"spoken"]'), 'Voice must not reuse dashboard maneuver labels');
assert(bridge.includes('YLNavigationSpeech(dir.rgCode, dir.nodeName, dir.directionNames, metres)'));
assert(!bridge.includes('회전 교차로에서 첫 번째 출구'), 'Clock direction must not become ordinal exit');
assert(!bridge.includes('졸음쉼터로 진입합니다'), 'Nearby rest area is not a route instruction');
assert(!bridge.includes('구간 단속이 끝났습니다'), 'Upcoming endpoint is not completed section');
assert(bridge.includes('directionFreqModeNormalWay = mode'));
assert(!bridge.includes('if (self.guiding && self.locationGuide.location) return YES;'));
assert(!bridge.includes('roadLaneSource'), 'Do not invent actual road lanes from road names');
assert(navigation.includes('Self.usableLocation(point)'));
assert(!navigation.includes('latitude: 37.5665'), 'No synthetic current position');
assert(read('DrivingWorkspace').includes('lastRequest != recenterRequest'));
assert(!read('DrivingWorkspace').includes('차량 위치를 중심으로 지도를 맞췄습니다.'));
const presentation = read('NavigationDashboard').split('func scenePresentation(theme:')[1].split('// MARK: - Metrics')[0];
assert(presentation.includes('"roadLane": -1'));
assert(!presentation.includes('suggestedLane'));
assert(!presentation.includes('"roadPath"'));
